---kategorisi kýrtasiye olan müþteri adeti getirsin

SELECT NAMESURNAME,SUM(AMOUNT) AS ADET FROM ORDERS O 
INNER JOIN ORDERDETAILS OD ON O.ID = OD.ORDERID
INNER JOIN USERS U ON U.ID = O.USERID
WHERE AGE=85 
AND YEAR(DATE_)=2020
AND OD.ITEMID IN (SELECT ITEMID FROM ITEMS WHERE CATEGORY3='KIRTASIYE')
GROUP BY NAMESURNAME
ORDER BY ADET DESC


