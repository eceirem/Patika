SELECT DISTINCT GENDER FROM USERS
---kadýn ya da erkek ya da diðerleri
SELECT 
CASE WHEN 
	GENDER ='K' THEN 'Kadýn'
	WHEN GENDER = 'E' THEN  'Erkek' ELSE GENDER END AS CINSIYETTANIM,
GENDER
FROM USERS
---kadýn ve diðerleri :)
SELECT 
CASE WHEN 
	GENDER ='K' THEN 'Kadýn'
	ELSE 'Erkek' END AS CINSIYETTANIM,
GENDER
FROM USERS

---yaþ aralýklarýna göre kategorize et
SELECT
CASE WHEN AGE BETWEEN 10 AND 30 THEN 'GENC'
WHEN AGE BETWEEN 31 AND 45 THEN 'ORTAYAS'
WHEN AGE BETWEEN 46 AND 60 THEN 'ORTAYASUSTU'
ELSE 'YASLI' END AS YASGRUBU, AGE, * 
FROM USERS
WHERE AGE = 0

---Eðer yaþ deðeri yanlýþ girilmiþ/boþ veri varsa 'BOS' yaz

SELECT
CASE WHEN AGE BETWEEN 10 AND 30 THEN 'GENC'
WHEN AGE BETWEEN 31 AND 45 THEN 'ORTAYAS'
WHEN AGE BETWEEN 46 AND 60 THEN 'ORTAYASUSTU'
WHEN AGE > 61 THEN 'YASLI'
ELSE 'BOS' END AS YASGRUBU, AGE, * 
FROM USERS

SELECT 
CASE WHEN LINETOTAL BETWEEN 10 AND 30 THEN 'AZ'
WHEN LINETOTAL BETWEEN 31 AND 50 THEN 'ORTA'
WHEN LINETOTAL BETWEEN 51 AND 99 THEN 'UST'
WHEN LINETOTAL BETWEEN 100 AND 200 THEN 'LUKS'
ELSE 'NO_INFO' 
END + ' GELIR' AS GELIRGRUPCONCAT,
LINETOTAL
FROM SALEORDERS

